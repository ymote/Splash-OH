//! Splash DSL → native ArkUI widgets.
//!
//! This is the piece that makes the repo's claim true: the widget tree is not
//! written in Rust, it is **evaluated by the Splash VM** (`makepad-script`) at
//! runtime and then walked into ArkUI nodes. The VM is renderer-free — it has
//! no dependency on makepad-platform, makepad-draw or any widget crate — so
//! nothing about makepad's renderer comes along for the ride.
//!
//! ## The tree the DSL produces
//!
//! A node is a plain object with a `t` type tag, optional attributes, and an
//! optional `c` array of children:
//!
//! ```text
//! {t: "column", bg: 0xFFF2F2F7, c: [
//!     {t: "text", text: "Components", size: 28, weight: 7},
//!     {t: "button", label: "Tap me", h: 44},
//! ]}
//! ```
//!
//! Deliberately plain data rather than makepad's `Button{...}` component
//! syntax: that syntax resolves through makepad's *widget registry*, which is
//! exactly the coupling this repo exists to avoid. Everything that makes the
//! DSL worth having is still available above this layer — variables, `fn`,
//! loops, conditionals, string building — because a real VM evaluates it. The
//! catalog leans on that heavily (see `assets/catalog.splash`).

use crate::arkui::{attr, event, ty, Node};
// The VM comes from ymote/Splash, which re-exports it as `vm` from its own
// pinned vendored copy. Importing it under the old name keeps the walk below
// unchanged; what changes is provenance, not API.
use splash_core::vm as makepad_script;

use makepad_script::apply::*;
use makepad_script::array::ScriptArrayStorage;
use makepad_script::makepad_live_id::*;
use makepad_script::traits::*;
use makepad_script::*;

/// Evaluate the catalog for a given screen.
///
/// `screen` and `bench` are bound as ordinary `let`s prepended to the source —
/// the simplest way to pass host state into a script without a scope object.
pub fn build_screen(screen: &str, bench: Option<&str>) -> Option<Node> {
    const CATALOG: &str = include_str!("../assets/catalog.splash");
    let esc = |s: &str| {
        s.replace('\\', "\\\\")
            .replace('"', "\\\"")
            .replace('\n', "\\n")
    };
    // `text_lines` in the DSL estimates wrapped height from `s.len()`, which
    // cannot see embedded newlines — the benchmark report has plenty, and it
    // overflowed its card. Rust can just count them properly and pass the
    // answer down.
    let report = bench.unwrap_or("");
    let src = format!(
        "let screen = \"{}\"\nlet bench = \"{}\"\nlet bench_lines = {}\n{}",
        esc(screen),
        esc(report),
        display_lines(report, BENCH_CHARS_PER_LINE),
        CATALOG
    );
    build(&src)
}

/// The component ids `catalog.splash` lists, in the order it lists them.
///
/// Generated by `build.rs` from the DSL itself, so the two cannot disagree —
/// see the note there for why this is generated rather than tested.
include!(concat!(env!("OUT_DIR"), "/catalog_screens.rs"));

/// Tap id the DSL uses for "open the screen at this index".
pub const CATALOG_NAV_BASE: i32 = 1000;
/// Tap id for the back button on a screen.
pub const CATALOG_NAV_BACK: i32 = 999;

/// Roughly how many characters fit on one line of the report, at the size and
/// width `catalog.splash` renders it. Matches the DSL's own 2.2 chars/vp rule.
const BENCH_CHARS_PER_LINE: usize = 63;

/// Wrapped line count, counting hard newlines as well as wrapping.
fn display_lines(s: &str, per_line: usize) -> usize {
    s.lines()
        .map(|l| {
            if l.is_empty() {
                1
            } else {
                l.len().div_ceil(per_line)
            }
        })
        .sum::<usize>()
        .max(1)
}

/// The flutter/samples kit, rendered to native ArkUI.
///
/// Same `.splash` source the makepad backend renders — vendored from
/// Splash-Makepad's `components/flutter/` by its `assemble` example. That the
/// identical kit drives two unrelated native toolkits is the whole point of the
/// UiNode split; this is the ArkUI half of it.
///
/// `route` picks the screen, `dark` the palette, exactly as the makepad host
/// injects them.
pub fn build_flutter(route: &str, dark: bool) -> Option<Node> {
    const KIT: &str = include_str!("../assets/flutter.splash");
    FLUTTER_ROUTES.with(|r| r.borrow_mut().clear());
    let src = format!(
        "let st = {{ route: {route:?}, dark: {}, t: {} }}\n{KIT}",
        u8::from(dark),
        elapsed_secs()
    );
    build(&src)
}

/// Tap ids for the flutter kit start here. The kit names its targets with
/// route *strings* (`tapto: "date_planner/maya"`), but ArkUI events carry an
/// i32, so the walk interns each route as it meets it and hands back an index.
pub const FLUTTER_NAV_BASE: i32 = 2000;

/// Seconds since the first mount, handed to the kit as `st.t`.
///
/// The DSL evaluates a tree once per mount and has no tween or controller, so
/// the only thing that can make a screen move is re-mounting it against a
/// changing clock. `anim_tick()` drives that from ArkTS.
fn elapsed_secs() -> f64 {
    use std::sync::OnceLock;
    use std::time::Instant;
    static START: OnceLock<Instant> = OnceLock::new();
    START.get_or_init(Instant::now).elapsed().as_secs_f64()
}

thread_local! {
    static FLUTTER_ROUTES: std::cell::RefCell<Vec<String>> =
        const { std::cell::RefCell::new(Vec::new()) };
}

/// Intern a route string, returning the tap id that stands for it.
fn intern_route(route: &str) -> i32 {
    FLUTTER_ROUTES.with(|r| {
        let mut v = r.borrow_mut();
        match v.iter().position(|s| s == route) {
            Some(i) => FLUTTER_NAV_BASE + i as i32,
            None => {
                v.push(route.to_string());
                FLUTTER_NAV_BASE + (v.len() - 1) as i32
            }
        }
    })
}

/// The route a tap id stands for, or `None` if it is not one of ours.
pub fn flutter_route(id: i32) -> Option<String> {
    if id < FLUTTER_NAV_BASE {
        return None;
    }
    FLUTTER_ROUTES.with(|r| r.borrow().get((id - FLUTTER_NAV_BASE) as usize).cloned())
}

/// Evaluate the LLM-generated weather card (`assets/weather.splash`) → native
